// ---- TEXT LAYOUT + RENDERING (uses render.ts Canvas) ----
import type { Canvas, RGB } from './render.ts';

const WIDTHS = [3, 4.5, 6.5]; // thin, mid, thick (glyph units)

export interface TextOpts {
  bold?: boolean;
  italic?: boolean;
  tracking?: number; // extra px between glyphs (final px)
  align?: 'left' | 'center' | 'right';
}

export function glyphWidth(ch: string, size: number, opts: TextOpts = {}): number {
  const g = GLYPHS[ch];
  if (!g) return size * 0.28;
  return (g.a * size) / 100 + (opts.tracking ?? 0);
}

export function measure(text: string, size: number, opts: TextOpts = {}): number {
  let w = 0;
  for (const ch of text) w += glyphWidth(ch, size, opts);
  return w;
}

// wrap text into lines that fit maxW (final px). Returns lines of words.
export function wrap(text: string, size: number, maxW: number, opts: TextOpts = {}): string[] {
  const words = text.split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    const test = cur ? cur + ' ' + w : w;
    if (measure(test, size, opts) <= maxW || !cur) cur = test;
    else { lines.push(cur); cur = w; }
  }
  if (cur) lines.push(cur);
  return lines;
}

// Draw text; x,y = baseline start (final-space coords). Returns end x.
export function drawText(cv: Canvas, text: string, x: number, y: number, size: number, color: RGB, opts: TextOpts = {}): number {
  const scale = size / 100;
  const boldMul = opts.bold ? 1.5 : 1;
  const slant = opts.italic ? -0.16 : 0;
  let cx = x;
  for (const ch of text) {
    const g = GLYPHS[ch];
    if (!g) { cx += size * 0.28; continue; }
    for (const st of g.s) {
      const wc = WIDTHS[st[0]] * boldMul;
      let wd = (wc * scale);
      wd = Math.max(wd, 0.95); // floor so small text never vanishes
      const pts: [number, number][] = [];
      for (let i = 1; i + 1 < st.length; i += 2) {
        const gx = st[i], gy = st[i + 1];
        const px = cx + gx * scale + slant * (0 - gy) * scale;
        const py = y - gy * scale;
        pts.push([px, py]);
      }
      if (pts.length === 1) {
        cv.circle(pts[0][0], pts[0][1], wd / 2, color);
      } else if (pts.length > 1) {
        cv.stroke(pts, wd, color);
      }
    }
    cx += (g.a * scale) + (opts.tracking ?? 0);
  }
  return cx;
}

export function drawTextAligned(cv: Canvas, text: string, cx: number, y: number, size: number, color: RGB, opts: TextOpts & { align?: 'left' | 'center' | 'right' } = {}): void {
  const w = measure(text, size, opts);
  let x = cx;
  if (opts.align === 'center') x = cx - w / 2;
  else if (opts.align === 'right') x = cx - w;
  drawText(cv, text, x, y, size, color, opts);
}
